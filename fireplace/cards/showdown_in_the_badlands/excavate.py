# Battlecry: Get 4 random spells. If you've Excavated 8 times, they
# cost (0). We resolve the picks ourselves so each gained spell can be
# reliably located in hand and (when zeroed) buffed.
class _AzeriteScorpionGet(TargetedAction):
	TARGET = ActionArg()

	def do(self, source, target):
		zero = target.excavates_this_game >= 8
		for _ in range(4):
			pick = RandomSpell().evaluate(source)
			cid = pick[0] if isinstance(pick, (list, tuple)) else pick
			if not cid:
				continue
			before = set(id(c) for c in target.hand)
			source.game.cheat_action(source, [Give(target, cid)])
			if not zero:
				continue
			for card in target.hand:
				if id(card) not in before:
					source.game.cheat_action(
						source, [Buff(card, "WW_001t23e")]
					)


class WW_001t23:
	"""The Azerite Scorpion"""

	play = _AzeriteScorpionGet(CONTROLLER)


