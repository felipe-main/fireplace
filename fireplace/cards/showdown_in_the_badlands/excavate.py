# Battlecry: Get a random Titan. It costs (1). Titans carry the
# DONT_PICK_FROM_SUBSETS tag, so they only surface from the card pool when
# can_pick_from_subsets is passed. We resolve the pick, give the card, then
# buff the freshly-added hand card to cost (1).
class _AzeriteHawkGet(TargetedAction):
	TARGET = ActionArg()

	def do(self, source, target):
		picker = RandomMinion(
			can_pick_from_subsets=True,
			custom_filter=lambda c: bool(getattr(c, "titan", False)),
		)
		pick = picker.evaluate(source)
		cid = pick[0] if isinstance(pick, (list, tuple)) else pick
		if not cid:
			return
		before = set(id(c) for c in target.hand)
		source.game.cheat_action(source, [Give(target, cid)])
		for card in target.hand:
			if id(card) not in before:
				source.game.cheat_action(source, [Buff(card, "WW_001t24e")])


class WW_001t24:
	"""The Azerite Hawk"""

	play = _AzeriteHawkGet(CONTROLLER)


