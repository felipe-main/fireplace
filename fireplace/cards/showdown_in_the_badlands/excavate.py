# Battlecry: Discover two 8-Cost minions. Summon them. Resolve the two
# discovers sequentially via a re-entrant action so the choices don't
# stomp on each other (flat Discover tuples all set player.choice at once
# and only the last survives — see CLAUDE.md).
class _AzeriteOxDiscover(TargetedAction):
	TARGET = ActionArg()

	def do(self, source, target):
		remaining = getattr(source, "_azerite_ox_left", None)
		if remaining is None:
			remaining = 2
		if remaining <= 0:
			source._azerite_ox_left = None
			return
		source._azerite_ox_left = remaining - 1
		source.game.cheat_action(
			source,
			[
				Discover(target, RandomMinion(cost=8)).then(
					Summon(target, Discover.CARD),
					_AzeriteOxDiscover(target),
				)
			],
		)


class WW_001t27:
	"""The Azerite Ox"""

	play = _AzeriteOxDiscover(CONTROLLER)
